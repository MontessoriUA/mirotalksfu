'use strict';

/*
 * Montemeet: тихая проба входа при заходе в урок.
 *
 * Зачем. Ссылка на урок одна для всех, и роль решает почта вошедшего, но по
 * этой ссылке войти никто не предлагает — студенты не из школьного домена, их
 * бы разворачивало на гугловском входе. Педагог, получивший ссылку руками,
 * попадал в собственный урок студентом, пока не сходит на сайт и не войдёт там
 * (заход Анны Росенко 25.11). Кнопку «я педагог» мы отвергли дважды: её видит и
 * студент, которому она незачем.
 *
 * Что делает. Спрашивает кабинет, не вошёл ли этот браузер под школьным
 * аккаунтом: `/mm/sso` уводит к Google с «тихим» режимом и тут же возвращает
 * обратно — с пропуском, если человек педагог этой комнаты, и просто обратно во
 * всех остальных случаях. Ничего не показывается и ничего не нажимается.
 *
 * Почему так рано и синхронно: уйти надо до того, как страница спросит камеру и
 * микрофон, иначе настройка устройств пропадёт при возврате. Этот файл
 * подключён без defer, выше остальных, и ничего не трогает в DOM.
 *
 * Пробуем один раз: кабинет ставит метку `mm_sso_tried` — на час перед уходом
 * (чтобы при любой неожиданности не случилось второго круга) и на месяц, если
 * школьного аккаунта в браузере не нашлось. У кого проба удалась, метка
 * снимается: пропуск живёт часы, и в следующий заход мы снова войдём молча.
 */

(function () {
    try {
        const path = String(location.pathname || '');
        const m = path.match(/^\/join\/([a-z0-9._-]+)/i);
        let room = m ? m[1] : '';
        if (!room) {
            try {
                room = new URL(location.href).searchParams.get('room') || '';
            } catch (e) {
                room = '';
            }
        }
        room = String(room).toLowerCase().replace(/[^a-z0-9._-]/g, '');
        if (!room) return;

        const hasCookie = (name) =>
            document.cookie.split(';').some((c) => c.trim().slice(0, name.length + 1) === name + '=');

        // Уже пробовали в этом браузере, или пропуск уже есть — не трогаем.
        if (hasCookie('mm_sso_tried') || hasCookie('mm_name')) return;

        // Второй пояс от круговой переадресации: в пределах вкладки пробуем раз.
        try {
            if (sessionStorage.getItem('mmSsoTried')) return;
            sessionStorage.setItem('mmSsoTried', '1');
        } catch (e) {
            /* хранилища нет — хватит куки-метки */
        }

        // Возвращаться — на этот же адрес целиком: параметры ссылки (имя,
        // «?notify=0» из расписания) иначе терялись — проба уводила на чистый
        // адрес комнаты (поймано тестом 27.11).
        const back = String(location.pathname || '') + String(location.search || '');
        location.replace('/mm/sso?room=' + encodeURIComponent(room) + '&back=' + encodeURIComponent(back));
    } catch (e) {
        /* что бы ни случилось — человек просто остаётся на странице урока */
    }
})();
